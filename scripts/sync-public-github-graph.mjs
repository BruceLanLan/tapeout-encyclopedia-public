import fs from "node:fs";
import path from "node:path";
import { stringify as stringifyYaml } from "yaml";

const root = process.cwd();
const catalogPath = path.join(
  root,
  "content",
  "public-github",
  "repositories.json",
);
const outputPath = path.join(
  root,
  "content",
  "graph",
  "public-github.yaml",
);
const catalog = JSON.parse(fs.readFileSync(catalogPath, "utf8"));

const repositoryEntityId = (fullName) =>
  `repo-${fullName
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")}`;

const ids = new Set();
const entities = catalog.map((repository) => {
  const id = repositoryEntityId(repository.full_name);
  if (ids.has(id)) {
    throw new Error(`Repository graph id collision: ${id}`);
  }
  ids.add(id);
  return {
    id,
    type: "repository",
    label: { zh: repository.full_name, en: repository.full_name },
    aliases: [],
    source_tier:
      repository.category === "official" ? "official" : "community",
    official_url: repository.url,
  };
});

const relations = catalog.map((repository) => {
  const from = repositoryEntityId(repository.full_name);
  return {
    id: `${from}-related-to-tapeout`,
    from,
    to: "tapeout",
    type: "related_to",
    confidence: repository.category === "official" ? "high" : "medium",
    source_tier:
      repository.category === "official" ? "official" : "community",
    sources: [repository.url],
  };
});

const header =
  "# Generated by npm run sync:public-github-graph. Do not edit by hand.\n";
fs.writeFileSync(
  outputPath,
  header + stringifyYaml({ entities, relations }, { lineWidth: 0 }),
);
console.log(
  `Wrote ${outputPath} (${entities.length} repository nodes, ${relations.length} edges)`,
);
